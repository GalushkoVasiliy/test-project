using FluentValidation;

namespace Rentals.Api.Features.Properties;

public sealed record PropertySummaryDto(
    Guid Id,
    string Name,
    string Address,
    string City,
    int UnitCount,
    int AvailableUnitCount,
    string Version);

public sealed record PropertyDetailsDto(
    Guid Id,
    string Name,
    string Address,
    string City,
    string Version,
    IReadOnlyList<UnitDto> Units);

public sealed record LeaseDto(Guid Id, Guid ApplicationId, DateOnly StartDate, DateOnly EndDate);

public sealed record UnitDto(
    Guid Id,
    Guid PropertyId,
    string UnitNumber,
    int Bedrooms,
    decimal MonthlyRent,
    int UnitTypeId,
    string UnitTypeName,
    bool UnitTypeIsActive,
    bool IsAvailable,
    LeaseDto? CurrentLease,
    int OpenApplicationCount,
    string Version);

public sealed record AvailableUnitDto(
    Guid Id,
    Guid PropertyId,
    string PropertyName,
    string PropertyAddress,
    string City,
    string UnitNumber,
    int Bedrooms,
    decimal MonthlyRent,
    string UnitTypeName);

public sealed record AvailableUnitsQuery(Guid? PropertyId, int? MinBedrooms, decimal? MaxRent);

/// <summary>The id is generated by the client, which makes replaying the request safe.</summary>
public sealed record CreatePropertyRequest(Guid Id, string Name, string Address, string City);

public sealed record UpdatePropertyRequest(string Name, string Address, string City, string Version);

/// <summary>The id is generated by the client, which makes replaying the request safe.</summary>
public sealed record CreateUnitRequest(Guid Id, string UnitNumber, int Bedrooms, decimal MonthlyRent, int UnitTypeId);

public sealed record UpdateUnitRequest(string UnitNumber, int Bedrooms, decimal MonthlyRent, int UnitTypeId, string Version);

public sealed record UnitTypeDto(int Id, string Name, bool IsActive);

internal static class PropertyRules
{
    public static void Name<T>(IRuleBuilder<T, string> rule) =>
        rule.NotEmpty().WithMessage("Name is required.").MaximumLength(120);

    public static void Address<T>(IRuleBuilder<T, string> rule) =>
        rule.NotEmpty().WithMessage("Address is required.").MaximumLength(200);

    public static void City<T>(IRuleBuilder<T, string> rule) =>
        rule.NotEmpty().WithMessage("City is required.").MaximumLength(100);

    public static void UnitNumber<T>(IRuleBuilder<T, string> rule) =>
        rule.NotEmpty().WithMessage("Unit number is required.").MaximumLength(20);

    public static void Bedrooms<T>(IRuleBuilder<T, int> rule) =>
        rule.InclusiveBetween(0, 10).WithMessage("Bedrooms must be between 0 and 10.");

    public static void MonthlyRent<T>(IRuleBuilder<T, decimal> rule) =>
        rule.GreaterThan(0).WithMessage("Monthly rent must be greater than 0.")
            .LessThanOrEqualTo(100_000).WithMessage("Monthly rent must be at most 100,000.")
            .PrecisionScale(10, 2, ignoreTrailingZeros: true).WithMessage("Monthly rent can have at most 2 decimal places.");
}

public sealed class CreatePropertyRequestValidator : AbstractValidator<CreatePropertyRequest>
{
    public CreatePropertyRequestValidator()
    {
        RuleFor(r => r.Id).NotEmpty();
        PropertyRules.Name(RuleFor(r => r.Name));
        PropertyRules.Address(RuleFor(r => r.Address));
        PropertyRules.City(RuleFor(r => r.City));
    }
}

public sealed class UpdatePropertyRequestValidator : AbstractValidator<UpdatePropertyRequest>
{
    public UpdatePropertyRequestValidator()
    {
        PropertyRules.Name(RuleFor(r => r.Name));
        PropertyRules.Address(RuleFor(r => r.Address));
        PropertyRules.City(RuleFor(r => r.City));
        RuleFor(r => r.Version).NotEmpty();
    }
}

public sealed class CreateUnitRequestValidator : AbstractValidator<CreateUnitRequest>
{
    public CreateUnitRequestValidator()
    {
        RuleFor(r => r.Id).NotEmpty();
        PropertyRules.UnitNumber(RuleFor(r => r.UnitNumber));
        PropertyRules.Bedrooms(RuleFor(r => r.Bedrooms));
        PropertyRules.MonthlyRent(RuleFor(r => r.MonthlyRent));
        RuleFor(r => r.UnitTypeId).GreaterThan(0).WithMessage("Unit type is required.");
    }
}

public sealed class UpdateUnitRequestValidator : AbstractValidator<UpdateUnitRequest>
{
    public UpdateUnitRequestValidator()
    {
        PropertyRules.UnitNumber(RuleFor(r => r.UnitNumber));
        PropertyRules.Bedrooms(RuleFor(r => r.Bedrooms));
        PropertyRules.MonthlyRent(RuleFor(r => r.MonthlyRent));
        RuleFor(r => r.UnitTypeId).GreaterThan(0).WithMessage("Unit type is required.");
        RuleFor(r => r.Version).NotEmpty();
    }
}
